import { test, expect } from '@playwright/test';
import type { Page, APIRequestContext } from '@playwright/test';
import { readFileSync } from 'node:fs';
import path from 'node:path';
async function register(page: Page, request: APIRequestContext) {
  const email = `browser-${Date.now()}@example.test`;
  await page.goto('/#/analysis');
  await expect(page.getByRole('heading', { name: 'Welcome back.' })).toBeVisible();
  await page.getByRole('button', { name: 'Create an account', exact: true }).click();
  await page.getByLabel('Name', { exact: true }).fill('EUN Test Researcher');
  await page.getByLabel('Email address').fill(email);
  await page.getByLabel('Password', { exact: true }).fill('EUN-Test-Password1!');
  await page.getByRole('button', { name: 'Create account', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Check your inbox.' })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Run sample', exact: true })).toHaveCount(0);
  const codes = await request.get('http://127.0.0.1:9099/emulator/v1/projects/demo-eun-v3/oobCodes');
  const code = (await codes.json()).oobCodes.find((c: { email: string; requestType: string }) => c.email === email && c.requestType === 'VERIFY_EMAIL');
  expect(code).toBeTruthy();
  const verified = await request.post('http://127.0.0.1:9099/identitytoolkit.googleapis.com/v1/accounts:update?key=demo-eun-v3', { data: { oobCode: code.oobCode } });
  expect(verified.ok()).toBeTruthy();
  await page.getByRole('button', { name: 'I’ve verified my email' }).click();
  await expect(page.getByRole('heading', { name: 'Every edit tells a story.' })).toBeVisible();
  return email;
}
test('required login, original sample, JSON/Excel/PNG/ZIP exports, mobile and logout', async ({ page, request }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  const email = await register(page, request);
  await page.screenshot({ path: 'test-results/analysis-desktop.png', fullPage: true });
  await page.getByRole('button', { name: 'Run sample', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Your results, in focus.' })).toBeVisible({ timeout: 150000 });
  await expect(page.getByText('14,568', { exact: true })).toBeVisible();
  const jsonDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download JSON', exact: true }).click();
  const jsonFile = await jsonDownload;
  const downloaded = JSON.parse(readFileSync((await jsonFile.path())!, 'utf8'));
  const original = JSON.parse(readFileSync('tests/fixtures/sample-report.json', 'utf8'));
  expect(downloaded).toEqual(original);
  const excelDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export Excel' }).click();
  expect((await excelDownload).suggestedFilename()).toMatch(/\.xlsx$/);
  await page.getByRole('tab', { name: 'Nucleotide frequencies' }).click();
  await expect(page.locator('.frequency-table')).toBeVisible();
  await page.getByRole('button', { name: 'View INDEL report' }).click();
  await expect(page.getByRole('heading', { name: 'See where change happens.' })).toBeVisible();
  const pngDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download PNG' }).click();
  expect((await pngDownload).suggestedFilename()).toMatch(/\.png$/);
  await page.getByLabel('From', { exact: true }).fill('20');
  await page.getByRole('button', { name: 'Reset zoom' }).click();
  await page.getByRole('link', { name: 'File conversion', exact: true }).click();
  await page.getByLabel('Choose JSON reports').setInputFiles(path.resolve('tests/fixtures/sample-report.json'));
  await page.getByLabel('Reverse sequence', { exact: false }).check();
  const zipDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Convert & download ZIP' }).click();
  expect((await zipDownload).suggestedFilename()).toBe('EUN_Convert_File.zip');
  await page.goto('/#/analysis');
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/analysis-mobile.png', fullPage: true });
  await page.getByRole('button', { name: 'Open menu' }).click();
  await page.getByRole('button', { name: 'Sign out', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Welcome back.' })).toBeVisible();
  await page.goto('/#/convert');
  await expect(page.getByRole('heading', { name: 'Welcome back.' })).toBeVisible();
  await page.getByLabel('Email address').fill(email);
  await page.getByLabel('Password', { exact: true }).fill('wrong-password');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('incorrect');
  await page.getByLabel('Password', { exact: true }).fill('EUN-Test-Password1!');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'A new perspective on your data.' })).toBeVisible();
  await page.goto('/#/history');
  await expect(page.getByRole('heading', { name: 'A clean slate.' })).toBeVisible();
  expect(errors).toEqual([]);
});

test('local results survive reload and login, and the reference stays visible while scrolling', async ({ page, request }) => {
  const email = await register(page, request);
  await page.getByRole('link', { name: 'Settings', exact: true }).click();
  const toggle = page.getByRole('switch', { name: 'Save results on this device' });
  await expect(toggle).toHaveAttribute('aria-checked', 'false');
  await toggle.click();
  await expect(toggle).toHaveAttribute('aria-checked', 'true');
  await page.getByRole('link', { name: 'Results history', exact: true }).click();
  await page.getByLabel('Import JSON report').setInputFiles(path.resolve('tests/fixtures/sample-report.json'));
  await expect(page.getByRole('heading', { name: 'Your results, in focus.' })).toBeVisible();
  await expect(page.getByRole('status')).toContainText('Saved on this device');
  const reportUrl = page.url();
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Your results, in focus.' })).toBeVisible();
  await expect(page.getByText('14,568', { exact: true })).toBeVisible();
  for (const viewport of [{ width: 1440, height: 1000 }, { width: 390, height: 844 }]) {
    await page.setViewportSize(viewport);
    await page.evaluate(() => window.scrollTo(0, 0));
    const reference = page.getByRole('region', { name: 'Reference amplicon', exact: true });
    const start = await reference.evaluate(element => element.getBoundingClientRect().top + window.scrollY);
    await page.evaluate(top => window.scrollTo(0, top + 350), start);
    await expect.poll(async () => (await reference.boundingBox())?.y ?? -1).toBeGreaterThanOrEqual(7);
    await expect.poll(async () => (await reference.boundingBox())?.y ?? 1000).toBeLessThanOrEqual(13);
    expect((await reference.boundingBox())!.height).toBeLessThanOrEqual(viewport.height * .43);
    await expect(reference).toBeInViewport({ ratio: 1 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: `test-results/reference-pinned-${viewport.width}.png` });
  }
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByRole('button', { name: 'Sign out', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Welcome back.' })).toBeVisible();
  await page.getByLabel('Email address').fill(email);
  await page.getByLabel('Password', { exact: true }).fill('EUN-Test-Password1!');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Your results, in focus.' })).toBeVisible();
  expect(page.url()).toBe(reportUrl);
  await page.getByRole('link', { name: 'Results history', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Open sample-report', exact: true })).toBeVisible();
});
